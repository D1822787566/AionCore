use std::collections::HashMap;
use std::sync::Arc;

use aionui_api_types::{
    BAITONG_PROVIDER_ID, CreateProviderRequest, ModelSettings, ProviderResponse, UpdateProviderRequest,
};
use aionui_common::{decrypt_string, encrypt_string};
use aionui_db::{CreateProviderParams, IProviderRepository, UpdateProviderParams, models::Provider};
use serde::de::DeserializeOwned;

use crate::error::SystemError;

/// Row content AionCore owns for the built-in Baitong provider.
///
/// Deliberately primitive: `aionui-system` must not depend on
/// `aionui-baitong`. The caller (`aionui-app`) translates the adapter's status
/// into this shape.
#[derive(Debug, Clone)]
pub struct ManagedProviderUpsert<'a> {
    pub id: &'a str,
    pub platform: &'a str,
    pub name: &'a str,
    pub base_url: &'a str,
    pub api_key: &'a str,
    pub models: &'a [String],
    pub model_settings: &'a HashMap<String, ModelSettings>,
}

/// Business logic for model provider CRUD with API key encryption/masking.
#[derive(Clone)]
pub struct ProviderService {
    repo: Arc<dyn IProviderRepository>,
    encryption_key: [u8; 32],
}

impl ProviderService {
    pub fn new(repo: Arc<dyn IProviderRepository>, encryption_key: [u8; 32]) -> Self {
        Self { repo, encryption_key }
    }

    /// List all providers with masked API keys.
    pub async fn list(&self, user_id: &str) -> Result<Vec<ProviderResponse>, SystemError> {
        let rows = self.repo.list(user_id).await?;
        rows.into_iter().map(|row| self.row_to_response(row)).collect()
    }

    /// Create a new provider. The API key is encrypted before storage.
    ///
    /// If `req.id` is `Some`, the caller-supplied id is used (after validation);
    /// otherwise a fresh id is generated by the repository. This supports the
    /// frontend-local-store → backend migration path where existing provider
    /// ids must be preserved.
    pub async fn create(&self, user_id: &str, req: CreateProviderRequest) -> Result<ProviderResponse, SystemError> {
        validate_create_request(&req)?;

        // Reserved id. `upsert_managed` is the only writer of this row, and
        // `delete` refuses it, so a user-created row under this id would be
        // stuck: unremovable from the UI, and pointing at whatever endpoint
        // the create call named until the next Baitong publish overwrote it.
        if req.id.as_deref().map(str::trim) == Some(BAITONG_PROVIDER_ID) {
            return Err(SystemError::BadRequest(
                "baitong-builtin is managed by AionCore and cannot be created manually".into(),
            ));
        }

        let encrypted_key = encrypt_string(&req.api_key, &self.encryption_key)?;
        let models_json = serialize_json(&req.models, "models")?;
        let capabilities_json = serialize_json(&req.capabilities, "capabilities")?;
        let model_protocols_json = serialize_opt(&req.model_protocols, "model_protocols")?;
        let model_enabled_json = serialize_opt(&req.model_enabled, "model_enabled")?;
        let model_health_json = serialize_opt(&req.model_health, "model_health")?;
        let model_settings_json = serialize_json(&req.model_settings, "model_settings")?;
        let bedrock_json = serialize_opt(&req.bedrock_config, "bedrock_config")?;
        let trimmed_id = req.id.as_deref().map(str::trim);

        let params = CreateProviderParams {
            id: trimmed_id,
            user_id,
            platform: &req.platform,
            name: &req.name,
            base_url: &req.base_url,
            api_key_encrypted: &encrypted_key,
            models: &models_json,
            enabled: req.enabled,
            capabilities: &capabilities_json,
            context_limit: req.context_limit,
            model_protocols: model_protocols_json.as_deref(),
            model_enabled: model_enabled_json.as_deref(),
            model_health: model_health_json.as_deref(),
            model_settings: &model_settings_json,
            bedrock_config: bedrock_json.as_deref(),
            is_full_url: req.is_full_url,
        };

        let row = self.repo.create(params).await?;
        self.row_to_response(row)
    }

    /// Update an existing provider. Only provided fields are changed.
    pub async fn update(
        &self,
        user_id: &str,
        id: &str,
        req: UpdateProviderRequest,
    ) -> Result<ProviderResponse, SystemError> {
        // The built-in row is content-owned by the adapter's status. The
        // frontend's provider editor sends a full row back on every toggle, so
        // this guard cannot live at the route: dropping the managed fields here
        // is what keeps a model-enable click from rewriting the model catalog or
        // the base URL. `enabled` and `model_enabled` stay honoured — those are
        // the user's own choices.
        let req = if id == BAITONG_PROVIDER_ID {
            UpdateProviderRequest {
                enabled: req.enabled,
                model_enabled: req.model_enabled,
                // Health-check results are the user's own probes, not adapter
                // content, so they pass through and get pruned on refresh.
                model_health: req.model_health,
                ..UpdateProviderRequest::default()
            }
        } else {
            req
        };

        validate_update_request(&req)?;

        let encrypted_key = req
            .api_key
            .as_deref()
            .map(|k| encrypt_string(k, &self.encryption_key))
            .transpose()?;
        let models_json = serialize_opt(&req.models, "models")?;
        let capabilities_json = serialize_opt(&req.capabilities, "capabilities")?;
        let model_protocols_json = serialize_opt(&req.model_protocols, "model_protocols")?;
        let model_enabled_json = serialize_opt(&req.model_enabled, "model_enabled")?;
        let model_health_json = serialize_opt(&req.model_health, "model_health")?;
        let model_settings_json = serialize_opt(&req.model_settings, "model_settings")?;
        let bedrock_json = serialize_opt(&req.bedrock_config, "bedrock_config")?;

        let params = UpdateProviderParams {
            platform: req.platform.as_deref(),
            name: req.name.as_deref(),
            base_url: req.base_url.as_deref(),
            api_key_encrypted: encrypted_key.as_deref(),
            models: models_json.as_deref(),
            enabled: req.enabled,
            capabilities: capabilities_json.as_deref(),
            context_limit: req.context_limit.map(Some),
            model_protocols: model_protocols_json.as_ref().map(|s| Some(s.as_str())),
            model_enabled: model_enabled_json.as_ref().map(|s| Some(s.as_str())),
            model_health: model_health_json.as_ref().map(|s| Some(s.as_str())),
            model_settings: model_settings_json.as_deref(),
            bedrock_config: bedrock_json.as_ref().map(|s| Some(s.as_str())),
            is_full_url: req.is_full_url,
        };

        let row = self.repo.update(user_id, id, params).await?;
        self.row_to_response(row)
    }

    /// Delete a provider by ID.
    pub async fn delete(&self, user_id: &str, id: &str) -> Result<(), SystemError> {
        // Content-owned row: deleting it would leave Baitong logged in with no
        // model provider until the next login republished it. Logout is the
        // supported way to remove it from the picker.
        if id == BAITONG_PROVIDER_ID {
            return Err(SystemError::BadRequest(
                "baitong-builtin is managed by AionCore and cannot be deleted".into(),
            ));
        }
        self.repo.delete(user_id, id).await?;
        Ok(())
    }

    /// Create or refresh the built-in provider row from adapter-owned content.
    ///
    /// Skips the write entirely when the stored row already matches
    /// `models` / `model_settings` / `base_url`, so repeated logins do not bump
    /// `updated_at` or push a needless provider event.
    ///
    /// `model_enabled` is preserved for models that still exist and dropped for
    /// models that left the catalog; a new model defaults to enabled.
    pub async fn upsert_managed(&self, user_id: &str, spec: ManagedProviderUpsert<'_>) -> Result<(), SystemError> {
        let models_json = serialize_json(&spec.models.to_vec(), "models")?;
        let model_settings_json = serialize_json(spec.model_settings, "model_settings")?;
        let encrypted_key = encrypt_string(spec.api_key, &self.encryption_key)?;

        let existing = self.repo.find_by_id(user_id, spec.id).await?;

        let Some(row) = existing else {
            let capabilities_json = serialize_json(&Vec::<aionui_api_types::ModelCapability>::new(), "capabilities")?;
            self.repo
                .create(CreateProviderParams {
                    id: Some(spec.id),
                    user_id,
                    platform: spec.platform,
                    name: spec.name,
                    base_url: spec.base_url,
                    api_key_encrypted: &encrypted_key,
                    models: &models_json,
                    enabled: true,
                    capabilities: &capabilities_json,
                    context_limit: None,
                    model_protocols: None,
                    model_enabled: None,
                    model_health: None,
                    model_settings: &model_settings_json,
                    bedrock_config: None,
                    is_full_url: false,
                })
                .await?;
            return Ok(());
        };

        // Content comparison. `model_settings` is compared as parsed JSON so
        // key order in the serialized form can never cause a false "changed".
        let stored_models: Vec<String> = serde_json::from_str(&row.models).unwrap_or_default();
        let stored_settings: HashMap<String, ModelSettings> =
            serde_json::from_str(&row.model_settings).unwrap_or_default();
        let content_unchanged = stored_models == *spec.models
            && stored_settings == *spec.model_settings
            && row.base_url == spec.base_url
            && row.platform == spec.platform;
        if content_unchanged {
            return Ok(());
        }

        let pruned_enabled = prune_model_enabled(&row.model_enabled, spec.models);
        let pruned_health = prune_keys(&row.model_health, spec.models);

        self.repo
            .update(
                user_id,
                spec.id,
                UpdateProviderParams {
                    platform: Some(spec.platform),
                    name: Some(spec.name),
                    base_url: Some(spec.base_url),
                    api_key_encrypted: Some(&encrypted_key),
                    models: Some(&models_json),
                    // `enabled` is the user's switch; content refresh must not
                    // flip it. Login/logout do that through `set_managed_enabled`.
                    enabled: None,
                    capabilities: None,
                    context_limit: None,
                    model_protocols: None,
                    // `None` here means "leave the column alone": when the row
                    // had no per-model map there is nothing to prune, and
                    // writing an empty object would be a spurious change.
                    model_enabled: pruned_enabled.as_ref().map(|json| Some(json.as_str())),
                    model_health: pruned_health.as_ref().map(|json| Some(json.as_str())),
                    model_settings: Some(&model_settings_json),
                    bedrock_config: None,
                    is_full_url: Some(false),
                },
            )
            .await?;
        Ok(())
    }

    /// Set `enabled` on the built-in provider row without touching its content.
    ///
    /// A no-op when the row does not exist yet: "enable" before any successful
    /// login has nothing to enable, and "disable" already is the desired state.
    pub async fn set_managed_enabled(&self, user_id: &str, enabled: bool) -> Result<(), SystemError> {
        let Some(row) = self.repo.find_by_id(user_id, BAITONG_PROVIDER_ID).await? else {
            return Ok(());
        };
        if row.enabled == enabled {
            return Ok(());
        }
        self.repo
            .update(
                user_id,
                BAITONG_PROVIDER_ID,
                UpdateProviderParams {
                    platform: None,
                    name: None,
                    base_url: None,
                    api_key_encrypted: None,
                    models: None,
                    enabled: Some(enabled),
                    capabilities: None,
                    context_limit: None,
                    model_protocols: None,
                    model_enabled: None,
                    model_health: None,
                    model_settings: None,
                    bedrock_config: None,
                    is_full_url: None,
                },
            )
            .await?;
        Ok(())
    }

    // -----------------------------------------------------------------------
    // Internal helpers
    // -----------------------------------------------------------------------

    /// Convert a DB row into a response DTO with the plaintext API key
    /// (decrypted) and deserialized JSON fields.
    ///
    /// Pre-launch: the response returns the API key in plaintext so the
    /// frontend can migrate its local store to the backend without losing
    /// the key on re-read. Storage remains encrypted at rest.
    fn row_to_response(&self, row: Provider) -> Result<ProviderResponse, SystemError> {
        // Lenient on decryption: a credential encrypted under a rotated/lost
        // key (e.g. one saved during the ELECTRON-3T0 broken session, whose
        // in-memory-only key is gone forever) must not take the whole
        // provider list down. Surface the row with an empty api_key so the
        // user can see it and re-enter the key; log at warn for production
        // diagnosability.
        let api_key = match decrypt_string(&row.api_key_encrypted, &self.encryption_key) {
            Ok(key) => key,
            Err(error) => {
                tracing::warn!(
                    provider_id = %row.id,
                    provider_name = %row.name,
                    %error,
                    "provider api_key failed to decrypt; returning empty key so the row stays visible for re-entry"
                );
                String::new()
            }
        };

        let models: Vec<String> = serde_json::from_str(&row.models)
            .map_err(|e| SystemError::Internal(format!("Failed to parse models JSON: {e}")))?;
        let capabilities = serde_json::from_str(&row.capabilities)
            .map_err(|e| SystemError::Internal(format!("Failed to parse capabilities JSON: {e}")))?;
        let model_protocols: Option<HashMap<String, String>> =
            deserialize_opt(&row.model_protocols, "model_protocols")?;
        let model_enabled: Option<HashMap<String, bool>> = deserialize_opt(&row.model_enabled, "model_enabled")?;
        let model_health = deserialize_opt(&row.model_health, "model_health")?;
        let model_settings = serde_json::from_str(&row.model_settings)
            .map_err(|e| SystemError::Internal(format!("Failed to parse model_settings JSON: {e}")))?;
        let bedrock_config = deserialize_opt(&row.bedrock_config, "bedrock_config")?;

        Ok(ProviderResponse {
            id: row.id,
            platform: row.platform,
            name: row.name,
            base_url: row.base_url,
            api_key,
            models,
            enabled: row.enabled,
            capabilities,
            context_limit: row.context_limit,
            model_protocols,
            model_enabled,
            model_health,
            model_settings,
            bedrock_config,
            is_full_url: row.is_full_url,
            created_at: row.created_at,
            updated_at: row.updated_at,
        })
    }
}

